export const placeholderImages = Object.fromEntries(
  IMAGE_ENTRIES.map((entry) => [ entry.id, entry ]),
);

export const placeholderImageList = IMAGE_ENTRIES;

export const imagesAwaitingArt = IMAGE_ENTRIES.filter((entry) => entry.status === "needed");

// @param {string} imageId - key from placeholderImages
// @returns {object} the manifest entry, or a loud fallback so a typo is visible on the page
export function findPlaceholderImage(imageId) {
  return (
    placeholderImages[imageId] || {
      id: imageId,
      status: "needed",
      file: null,
      subject: `Unknown image id "${imageId}"`,
      alt: "",
      aspectRatio: "3 / 2",
      targetSize: "",
      replacementNotes: "",
    }
  );
}
